"use strict";
const assert = require("node:assert/strict"), path = require("node:path");
const probe = globalThis.__leflectPackageProbe;
module.exports = async function verify(api, mode) {
  const checks = [];
  const check = (name, test) => { assert.ok(test, name); checks.push(name); };
  const root = path.join(process.cwd(), "source");
  const normalized = value => value.replaceAll("\\", "/");
  const point = (source, offset) => {
    const prefix = source.slice(0, offset).split("\n");
    return { line: prefix.length, column: prefix.at(-1).length + 1 };
  };
  const range = (source, raw) => {
    const start = point(source, source.indexOf(raw)), end = point(source, source.indexOf(raw) + raw.length - 1);
    return { startLine: start.line, startColumn: start.column, endLine: end.line, endColumn: end.column };
  };
  for (const key of ["analyzeWorkspace", "run", "parseJsp", "parseTld", "loadTldRegistry"]) check(`${mode} named ${key}`, typeof api[key] === "function");
  probe.phase("pure");
  const source = '<div data-id="${customer.id}">한😀<span>v</span>\r\n<bank:task code="BANK_01"/></div>';
  const jsp = api.parseJsp(source, { sourceKind: "jsp" });
  check("parseJsp is synchronous", !(jsp instanceof Promise));
  check("document root contract", jsp.document.kind === "Document" && Array.isArray(jsp.document.children));
  const div = jsp.document.children.find(node => node.kind === "HtmlElement");
  assert.deepEqual(div.lineRange, range(source, source));
  assert.equal(div.attributes["data-id"], "${customer.id}");
  const span = div.children.find(node => node.kind === "HtmlElement");
  assert.deepEqual(span.lineRange, range(source, '<span>v</span>'));
  const task = div.children.find(node => node.kind === "CustomTagElement");
  assert.deepEqual(task.lineRange, range(source, '<bank:task code="BANK_01"/>'));
  assert.equal(task.attributes.code, "BANK_01");
  assert.equal(task.prefix, "bank");
  const el = div.attributeNodes.flatMap(node => node.children).find(node => node.kind === "ElExpression");
  assert.equal(el.ast.kind, "PropertyAccessExpression");
  assert.equal(el.ast.target.kind, "IdentifierExpression");
  assert.equal(el.ast.target.name, "customer");
  assert.equal(el.ast.property, "id");
  check("JSP child/attribute/EL and UTF-16 inclusive ranges", true);
  const tld = api.parseTld('<taglib><uri>urn:poc:xml</uri><tag><name>task</name><tag-class>example.TaskTag</tag-class><attribute><name>code</name><required>true</required><rtexprvalue>true</rtexprvalue><type>java.lang.String</type></attribute></tag></taglib>');
  check("parseTld is synchronous", !(tld instanceof Promise));
  assert.equal(tld.uri, "urn:poc:xml");
  assert.equal(tld.tags[0].handlerClass, "example.TaskTag");
  assert.deepEqual(tld.tags[0].attributes[0], { name: "code", required: true, runtimeExpressionValue: true, type: "java.lang.String", fragment: undefined });
  check("TLD string URI/handler/attribute contract", true);
  const start = probe.phase("empty");
  const emptyPromise = api.loadTldRegistry({ root, repoFiles: [], configuredPaths: [], classpathEntries: [], autoLoad: true });
  check("loadTldRegistry is asynchronous", emptyPromise instanceof Promise);
  assert.deepEqual(await emptyPromise, { entries: [], diagnostics: [] });
  check("empty lists perform zero filesystem access", probe.since(start).length === 0);
  const selected = path.join(root, "repo", "selected.tld"), jar = path.join(root, "lib", "selected.jar");
  probe.phase("explicit", [selected, jar]);
  const explicit = await api.loadTldRegistry({ root, repoFiles: ["repo/selected.tld"], classpathEntries: [jar], autoLoad: true });
  assert.deepEqual(explicit.entries.map(entry => entry.uri), ["urn:poc:jar", "urn:poc:selected"]);
  const repo = explicit.entries.find(entry => entry.uri === "urn:poc:selected");
  assert.equal(repo.sourcePath, "repo/selected.tld");
  assert.equal(repo.sourceKind, "repo");
  assert.equal(repo.tags[0].handlerClass, "example.SelectedTag");
  assert.equal(repo.tags[0].attributes[0].name, "code");
  const loadedJar = explicit.entries.find(entry => entry.uri === "urn:poc:jar");
  assert.equal(loadedJar.sourcePath, normalized(jar) + "!/META-INF/allowed.tld");
  assert.equal(loadedJar.sourceKind, "classpath");
  assert.equal(explicit.diagnostics.length, 1);
  assert.equal(explicit.diagnostics[0].code, "duplicate-uri");
  assert.equal(explicit.diagnostics[0].uri, "urn:poc:selected");
  assert.equal(explicit.diagnostics[0].sourcePath, normalized(jar) + "!/META-INF/duplicate.tld");
  check("explicit repo TLD/JAR preserve URI/source/duplicates without traversal", true);
  const configured = path.join(root, "configured", "selected.tld");
  probe.phase("explicit-configured-file", [configured]);
  const one = await api.loadTldRegistry({ root, repoFiles: [], configuredPaths: [configured] });
  assert.deepEqual(one.entries.map(entry => entry.uri), ["urn:poc:configured"]);
  assert.equal(one.entries[0].sourcePath, normalized(configured));
  check("configured file does not expand to siblings", true);
  const configuredDir = path.join(root, "configured");
  probe.phase("configured-directory", [], [configuredDir]);
  const recursive = await api.loadTldRegistry({ root, repoFiles: [], configuredPaths: [configuredDir] });
  assert.deepEqual(recursive.entries.map(entry => entry.uri), ["urn:poc:configured", "urn:poc:recursive"]);
  check("explicit configured directory recurses within directory", true);
  const libraryDir = path.join(root, "lib");
  probe.phase("classpath-directory", [], [libraryDir]);
  const jars = await api.loadTldRegistry({ root, repoFiles: [], classpathEntries: [libraryDir], autoLoad: true });
  assert.deepEqual(jars.entries.map(entry => entry.uri), ["urn:poc:jar", "urn:poc:neighbor", "urn:poc:nested", "urn:poc:selected"]);
  check("classpath directory recurses through JARs without loose TLD discovery", true);
  probe.phase("explicit-entry", [jar]);
  const entry = await api.loadTldRegistry({ root, repoFiles: [], uriMap: { "urn:poc:override": "lib/selected.jar!/META-INF/allowed.tld" } });
  assert.deepEqual(entry.entries.map(item => item.uri), ["urn:poc:override"]);
  assert.equal(entry.entries[0].sourcePath, normalized(jar) + "!/META-INF/allowed.tld");
  check("explicit JAR entry does not expand to sibling entries", true);
  const evidence = probe.finish();
  check("import and parser functions never invoke Java/child processes or forbidden file access", evidence.blocked.length === 0);
  check("import and parser functions produce no CLI output", evidence.output.length === 0);
  return { mode, checks, exportedFunctions: Object.keys(api).filter(key => typeof api[key] === "function").sort(),
    importFilesystemReads: evidence.records.filter(row => row.phase === "import").length,
    discoveryOperations: evidence.records.filter(row => /readdir|opendir|glob/.test(row.method)), blocked: evidence.blocked, output: evidence.output };
};
